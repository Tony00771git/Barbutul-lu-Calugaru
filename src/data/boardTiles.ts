// Map perimeter indices 0..35 to 10x10 grid (10 cols: 1..10, 10 rows: 1..10)
// Perimeter: Top (0..9), Right (10..18), Bottom (19..27), Left (28..35)
export const calculateGridPos = (index: number): { gridRow: number; gridCol: number } => {
  if (index >= 0 && index <= 9) {
    // Top Row: Row 1, Col 1..10 (0 -> (1,1), 9 -> (1,10))
    return { gridRow: 1, gridCol: index + 1 };
  } else if (index >= 10 && index <= 18) {
    // Right Column: Col 10, Row 2..10 (10 -> (2,10), 18 -> (10,10))
    return { gridRow: (index - 10) + 2, gridCol: 10 };
  } else if (index >= 19 && index <= 27) {
    // Bottom Row: Row 10, Col 9..1 (19 -> (10,9), 27 -> (10,1))
    return { gridRow: 10, gridCol: 10 - (index - 18) };
  } else {
    // Left Column: Col 1, Row 9..2 (28 -> (9,1), 35 -> (2,1))
    return { gridRow: 10 - (index - 27), gridCol: 1 };
  }
};

