// Map perimeter indices 0..29 to 9x8 grid (9 cols: 0..8, 8 rows: 0..7)
export const calculateGridPos = (index: number): { gridRow: number; gridCol: number } => {
  if (index >= 0 && index <= 8) {
    // Top Row: Row 1 (1-indexed CSS grid), Col 1..9
    return { gridRow: 1, gridCol: index + 1 };
  } else if (index >= 9 && index <= 14) {
    // Right Column: Col 9, Row 2..7
    return { gridRow: (index - 9) + 2, gridCol: 9 };
  } else if (index >= 15 && index <= 23) {
    // Bottom Row: Row 8, Col 9..1 (going backwards)
    return { gridRow: 8, gridCol: 9 - (index - 15) };
  } else {
    // Left Column: Col 1, Row 7..2 (going upwards)
    return { gridRow: 8 - (index - 23), gridCol: 1 };
  }
};

